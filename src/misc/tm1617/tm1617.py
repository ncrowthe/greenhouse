# Tens-digit pattern for the minus sign: only the middle (g) segment.
# Derived from the table above: "0" -> "8" differs by 0x20 in byte 0,
# so 0x20 is segment g.
_LED_MINUS = (0x20, 0x00)

# "Er" error text (tens digit = E, ones digit = r), built from the segment
# mapping implied by digit_patterns:
#   a=b1&0x02 b=b1&0x04 c=b1&0x01 d=b0&0x40 e=b0&0x80 f=b0&0x10 g=b0&0x20
_LED_E = (0xF0, 0x02)   # a, f, g, e, d
_LED_R = (0xA0, 0x00)   # e, g (lowercase r)

LED_MIN_NUMBER = -9
LED_MAX_NUMBER = 99


class TM1617LED:
    """
    Two-digit display driver (STB/CLK/DIO interface).

    Usage::

        display = TM1617LED(stb_pin=0, clk_pin=1, dio_pin=2)
        display.show_number(42)
        display.show_number(-9)
    """

    def __init__(self, stb_pin, clk_pin, dio_pin, brightness=7):
        self._stb = Pin(stb_pin, Pin.OUT, value=1)
        self._clk = Pin(clk_pin, Pin.OUT, value=1)
        self._dio = Pin(dio_pin, Pin.OUT, value=1)
        self._brightness = brightness & 0x07

        self._send_command(_LED_CMD_MODE_3G7S)
        self.clear()

    def _delay(self):
        time.sleep_us(2)

    def _write_byte(self, byte_data):
        """Shift out one byte, LSB first."""
        self._dio.init(mode=Pin.OUT)
        for i in range(8):
            self._clk.value(0)
            self._dio.value((byte_data >> i) & 0x01)
            self._delay()
            self._clk.value(1)
            self._delay()

    def _send_command(self, command):
        self._stb.value(0)
        self._delay()
        self._write_byte(command)
        self._stb.value(1)
        self._delay()

    def _write_ram(self, data):
        """Write bytes to display RAM starting at address 0 (auto-increment)."""
        self._send_command(_LED_CMD_DATA)
        self._stb.value(0)
        self._delay()
        self._write_byte(_LED_CMD_ADDR)
        for b in data:
            self._write_byte(b & 0xFF)
        self._stb.value(1)
        self._delay()
        self._send_command(_LED_CMD_DISPLAY | self._brightness)

    def brightness(self, level):
        """Set brightness 0 (dimmest) to 7 (brightest) and turn display on."""
        self._brightness = level & 0x07
        self._send_command(_LED_CMD_DISPLAY | self._brightness)

    def off(self):
        """Turn the display off (RAM retained)."""
        self._send_command(0x80)

    def clear(self):
        """Zero all display RAM, blanking the display."""
        self._write_ram([0x00] * _LED_RAM_SIZE)

    def show_raw(self, ones_pattern, tens_pattern):
        """Write raw 2-byte patterns for the ones and tens digits."""
        self._write_ram(list(ones_pattern) + list(tens_pattern))

    def show_number(self, n):
        """
        Show an integer from -9 to 99.

        0..99  -> two digits taken from digit_patterns (e.g. "07", "42")
        -9..-1 -> minus sign in the tens digit, value in the ones digit

        Raises ValueError for anything outside -9..99.
        """
        n = int(n)
        if n < LED_MIN_NUMBER or n > LED_MAX_NUMBER:
            self.show_raw(_LED_R, _LED_E)
            return

        if n < 0:
            self.show_raw(digit_patterns[-n][0:2], _LED_MINUS)
        else:
            self._write_ram(digit_patterns[n])

